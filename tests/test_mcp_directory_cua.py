"""Actual official Cua round trip through mdo's native directory packager."""
import argparse
import copy
import hashlib
import json
from pathlib import Path
import tempfile
import time
import sys
import uuid

from test_mcp_directory_install import NativeApp,ROOT,default_host
sys.path.insert(0,str(ROOT))
from computer_use import driver


def refresh(app,server="cua-driver"):
    op=app.request("/mcp/"+server+"/refresh",dict(operation_id="op-c-"+uuid.uuid4().hex),status=202)
    deadline=time.monotonic()+45
    while not op.get("terminal") and time.monotonic()<deadline:
        time.sleep(.1);op=app.request("/operations/"+op["id"])
    assert op.get("state")=="succeeded",op
    assert op["result"]["connected"] and op["result"]["discovered_tools"]==63,op
    if server!="cua-driver":return 63
    status=next(i for i in app.request("/mcp")["items"] if i["id"]=="cua-driver")
    assert status["connected"] and status["discovered_tool_count"]==63,status
    return status["discovered_tool_count"]


def main():
    parser=argparse.ArgumentParser();parser.add_argument("--host",type=Path,default=default_host())
    parser.add_argument("--driver-directory",type=Path,required=True)
    parser.add_argument("--package",type=Path,help="Reuse a package already generated by the native authoring round trip")
    args=parser.parse_args()
    official=driver.verify(args.driver_directory.resolve())
    output=ROOT/".build/computer-use";output.mkdir(parents=True,exist_ok=True)
    proof=dict(schema_version=1,driver_version=driver.LOCK["version"],model=False,official_files=len(driver.LOCK["files"]),
        host_sha256=hashlib.sha256(args.host.read_bytes()).hexdigest(),mdo_minimum_build=70000057,
        original_bytes=sum(f["bytes"] for f in driver.LOCK["files"].values()),passed=False)
    with tempfile.TemporaryDirectory(prefix="cua-directory-",dir=ROOT/".build") as raw:
        base=Path(raw)
        with NativeApp(base,args.host) as app:
            item=None
            if args.package:
                p=json.loads(args.package.read_text(encoding="utf-8"))
            else:
                print("Copying six official files through the native MCP authoring API",flush=True)
                cfg=driver.connection(official)
                item=app.request("/extensions/mcp/cua-driver",dict(content=json.dumps(cfg)),revision="new",method="PUT")
                item=app.request("/mcp/connections",dict(action="copy_program",id="cua-driver",directory=str(official.parent),confirm_copy=True),revision=item["revision"])
                exported=app.request("/ecosystem",dict(action="export",single_kind="mcp",references=[dict(kind="mcp",id="cua-driver")]))
                resource=exported["resources"][0];assert len(resource["files"])==6
                for f in resource["files"]:assert f["sha256"]==driver.LOCK["files"][f["path"]]["sha256"]
                public=json.loads((ROOT/"computer_use/template.json").read_text(encoding="utf-8"));public.update(format="mdo.mcp-template.v2",inputs=[])
                for v in public["variants"]:v["config"]["transport"].update(program="./cua-driver.exe",working_directory=".")
                resource["content"]=json.dumps(public,ensure_ascii=False,separators=(",",":"))
                p=driver.extension_package();p.update(format="mdo.extension.v2",resources=[resource]);p["manifest"].update(version="0.2.0",min_build_id=70000057,
                    readme="随包附带官方 Cua Driver 0.38.0 全部六个文件。安装后检查配置并启用；无需手动选择程序路径。现有浏览器访问须另行明确授权。")
            encoded=json.dumps(p,ensure_ascii=False,separators=(",",":")).encode()
            artifact=output/"computer-use.mdo-extension.json";artifact.write_bytes(encoded)
            proof.update(package_bytes=len(encoded),package_sha256=hashlib.sha256(encoded).hexdigest())
            print(f"Native package: {len(encoded)} bytes ({len(encoded)/1048576:.2f} MiB)",flush=True)
            if item:app.request("/extensions/mcp/cua-driver",revision=item["revision"],method="DELETE")
            print("Installing the package and starting Cua by its configuration-relative path",flush=True)
            app.request("/ecosystem",dict(action="import",single_kind="mcp",package=p))
            installed=app.home/"mcp/cua-driver";driver.verify(installed)
            item=app.request("/extensions/mcp/cua-driver")
            app.request("/extensions/mcp/cua-driver/enabled",dict(enabled=True),revision=item["revision"])
            proof["initial_tools"]=refresh(app)
            alias_body=dict(action="save",variant="windows",receipt_key="local:mdo-computer-use",values={},enabled=True,confirm_launch=True)
            alias=app.request("/mcp/connections",dict(alias_body,id="cua-alias"),revision="new")
            proof["personal_alias_tools"]=refresh(app,"cua-alias")
            project=app.request("/mcp/connections?project=default",dict(alias_body,id="cua-project"),revision="new")
            proof["project_tools"]=refresh(app,project["runtime_id"])
            print("Initial Cua discovery: 63 tools; checking update with a running driver",flush=True)
            updated=copy.deepcopy(p);updated["manifest"]["version"]="0.2.1"
            app.request("/ecosystem",dict(action="import",single_kind="mcp",package=updated))
            driver.verify(installed);proof["after_update_tools"]=refresh(app)
            proof["after_update_alias_tools"]=refresh(app,"cua-alias")
            proof["after_update_project_tools"]=refresh(app,project["runtime_id"])
            app.request("/mcp/connections",dict(action="delete",id="cua-alias"),revision=alias["revision"])
            app.request("/mcp/connections?project=default",dict(action="delete",id="cua-project"),revision=project["revision"])
            moved=base/"home-moved";app.request("/mcp/cua-driver/disconnect",method="POST")
        (base/"home").rename(moved)
        resumed=NativeApp(base,args.host);resumed.home=moved
        with resumed as app:
            print("Reopening the moved Home and testing the same relative entry",flush=True)
            proof["after_move_tools"]=refresh(app)
            app.request("/ecosystem",dict(action="uninstall",single_kind="mcp",entry=dict(source="local",slug="mdo-computer-use")))
            cfg_path=moved/"mcp/cua-driver/mcp.json"
            assert cfg_path.exists() and not json.loads(cfg_path.read_text(encoding="utf-8"))["enabled"]
            assert not (cfg_path.parent/"cua-driver.exe").exists()
            status=next(i for i in app.request("/mcp")["items"] if i["id"]=="cua-driver")
            assert not status["connected"] and not status["enabled"]
            proof["uninstalled_disabled"]=True
    driver.verify(official.parent);proof["passed"]=True
    (output/"directory-acceptance.json").write_text(json.dumps(proof,indent=2)+"\n",encoding="utf-8")
    print(json.dumps(proof,indent=2),flush=True)


if __name__=="__main__":main()
